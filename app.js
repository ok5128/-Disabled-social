function readExternalSession() {
  const injected = window.DaoxinAccount || window.UnifiedAccount || {};
  const searchParams = new URLSearchParams(window.location.search);
  const hashParams = new URLSearchParams(window.location.hash.replace(/^#/, ""));
  const userId = injected.user_id || injected.userId || searchParams.get("user_id") || hashParams.get("user_id") || "";
  const token = injected.token || searchParams.get("token") || hashParams.get("token") || "";
  return { userId: String(userId), token: String(token), ready: Boolean(token) };
}

async function businessFetch(path, options = {}) {
  if (!externalSession.ready) throw new Error(t("authMissing"));
  const headers = {
    "Content-Type": "application/json",
    Authorization: `Bearer ${externalSession.token}`,
    "X-User-Id": externalSession.userId,
    ...(options.headers || {}),
  };
  const response = await fetch(path, { ...options, headers });
  if (!response.ok) throw new Error(`Business API failed: ${response.status}`);
  return response.status === 204 ? null : response.json();
}

async function apiFetch(path, options = {}) {
  const headers = {
    "Content-Type": "application/json",
    ...(options.headers || {}),
  };
  const response = await fetch(path, { ...options, headers });
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(payload.message || payload.error || `${response.status}`);
  return payload;
}

