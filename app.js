function SpeechRecognitionConstructor() {
  return window.SpeechRecognition || window.webkitSpeechRecognition || null;
}

function startSpeechRecognition() {
  const Recognition = SpeechRecognitionConstructor();
  speechTranscript = "";
  if (!Recognition) return false;
  try {
    speechRecognition = new Recognition();
    speechRecognition.lang = lang === "zh" ? "zh-CN" : "en-US";
    speechRecognition.continuous = true;
    speechRecognition.interimResults = true;
    speechRecognition.onresult = (event) => {
      let finalText = "";
      let interimText = "";
      for (let index = 0; index < event.results.length; index += 1) {
        const result = event.results[index];
        const textValue = result[0]?.transcript || "";
        if (result.isFinal) finalText += textValue;
        else interimText += textValue;
      }
      speechTranscript = (finalText || interimText).trim();
    };
    speechRecognition.onerror = () => {};
    speechRecognition.start();
    return true;
  } catch {
    speechRecognition = null;
    return false;
  }
}

function stopSpeechRecognition() {
  if (!speechRecognition) return speechTranscript.trim();
  try {
    speechRecognition.stop();
  } catch {}
  speechRecognition = null;
  return speechTranscript.trim();
}

function recordingSupportMessage() {
  if (!window.isSecureContext) return lang === "zh" ? "当前页面不是安全上下文，浏览器不会开放麦克风。请用 http://127.0.0.1 或 https 域名打开。" : "This page is not a secure context. Open it with http://127.0.0.1 or HTTPS.";
  if (!navigator.mediaDevices?.getUserMedia) return t("recordingUnsupported");
  if (!window.MediaRecorder) return t("recordingUnsupported");
  if (!SpeechRecognitionConstructor()) return t("speechUnsupported");
  return "";
}

async function microphonePermissionState() {
  if (!navigator.permissions?.query) return "unknown";
  try {
    const result = await navigator.permissions.query({ name: "microphone" });
    return result.state || "unknown";
  } catch {
    return "unknown";
  }
}

async function startVoiceRecording(event) {
  if (recordingStarting || mediaRecorder) return;
  event?.preventDefault?.();
  event?.stopPropagation?.();
  recordingPointerId = event?.pointerId ?? null;
  recordingStarting = true;
  recordingStopRequested = null;
  recordingStartTime = Date.now();
  voiceButton.classList.add("is-recording");
  chatForm.classList.add("is-recording");
  voiceButton.innerHTML = mainModeMarkup("voice", t("releaseSend"));
  addMessage("ai", t("recordingRequesting"), "soul");
  recordingNotice = chatMessages.querySelector(".message:last-child");
  recordedChunks = [];
  if (event?.pointerId !== undefined && typeof voiceButton.setPointerCapture === "function") {
    try {
      voiceButton.setPointerCapture(event.pointerId);
    } catch {}
  }
  const supportMessage = recordingSupportMessage();
  if (supportMessage) {
    recordingStarting = false;
    resetRecordingUi();
    addMessage("ai", supportMessage, "soul");
    return;
  }
  try {
    const permissionState = await microphonePermissionState();
    if (permissionState === "denied") {
      recordingStarting = false;
      resetRecordingUi();
      addMessage("ai", t("recordingDenied"), "soul");
      return;
    }
    const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
    recordingStream = stream;
    mediaRecorder = new MediaRecorder(stream);
    mediaRecorder.addEventListener("dataavailable", (event) => {
      if (event.data.size) recordedChunks.push(event.data);
    });
    startSpeechRecognition();
    mediaRecorder.start(250);
    if (recordingNotice) {
      recordingNotice.querySelector(".bubble")?.replaceChildren(document.createTextNode(t("recordingNow")));
    }
    recordingStarting = false;
    if (recordingStopRequested !== null) stopVoiceRecording(recordingStopRequested);
  } catch {
    recordingStarting = false;
    mediaRecorder = null;
    stopRecordingStream();
    resetRecordingUi();
    addMessage("ai", t("recordingError"), "soul");
  }
}

function stopVoiceRecording(send = true, event = null) {
  if (event?.pointerId !== undefined && recordingPointerId !== null && event.pointerId !== recordingPointerId) return;
  event?.preventDefault?.();
  const transcript = stopSpeechRecognition();
  if (recordingStarting && !mediaRecorder) {
    recordingStopRequested = send;
    resetRecordingUi();
    return;
  }
  resetRecordingUi();
  if (!mediaRecorder) {
    if (send) addMessage("ai", t("recordingEmpty"), "soul");
    return;
  }

  const recorder = mediaRecorder;
  mediaRecorder = null;
  recordingPointerId = null;
  recorder.addEventListener(
    "stop",
    async () => {
      stopRecordingStream();
      if (!send) return;
      if (!recordedChunks.length || Date.now() - recordingStartTime < 250) {
        addMessage("ai", t("recordingEmpty"), "soul");
        return;
      }
      const blob = new Blob(recordedChunks, { type: recorder.mimeType || "audio/webm" });
      const fallbackSeconds = Math.max(1, (Date.now() - recordingStartTime) / 1000);
      const durationSeconds = await audioDurationForBlob(blob, fallbackSeconds);
      const localAudioSrc = URL.createObjectURL(blob);
      const file = new File([blob], `voice-${Date.now()}.webm`, { type: blob.type || "audio/webm" });
      // 语音修复：transcript 为空时仍发送语音消息
      const displayText = transcript || t("voiceMessage");
      if (!transcript) {
        console.warn("[daoxin] SpeechRecognition empty, using fallback");
      }
      addMessage("user", t("voiceSent"), "human", { type: "voice", audioSrc: localAudioSrc, durationSeconds });
      uploadFile(file).catch(() => {});
      replyLater(transcript || "你好", { type: "voice" });
    },
    { once: true },
  );
  if (recorder.state !== "inactive") {
    try {
      recorder.requestData();
    } catch {}
    recorder.stop();
  }
}

