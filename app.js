function formatVoiceDuration(seconds) {
  const safeSeconds = Math.max(1, Math.round(Number(seconds) || 1));
  if (safeSeconds < 60) return `${safeSeconds}"`;
  const minutes = Math.floor(safeSeconds / 60);
  const rest = String(safeSeconds % 60).padStart(2, "0");
  return `${minutes}:${rest}`;
}

function estimateSpeechDuration(textValue) {
  const value = String(textValue || "");
  const chineseChars = (value.match(/[\u4e00-\u9fff]/g) || []).length;
  const words = (value.replace(/[\u4e00-\u9fff]/g, " ").match(/[a-zA-Z0-9]+/g) || []).length;
  return Math.max(2, Math.min(45, Math.ceil(chineseChars / 4 + words / 2.5)));
}

function audioDurationForBlob(blob, fallbackSeconds) {
  return new Promise((resolve) => {
    const url = URL.createObjectURL(blob);
    const audio = new Audio();
    let settled = false;
    const finish = (value) => {
      if (settled) return;
      settled = true;
      URL.revokeObjectURL(url);
      resolve(Number.isFinite(value) && value > 0 ? value : fallbackSeconds);
    };
    audio.addEventListener("loadedmetadata", () => finish(audio.duration), { once: true });
    audio.addEventListener("error", () => finish(fallbackSeconds), { once: true });
    setTimeout(() => finish(fallbackSeconds), 1200);
    audio.preload = "metadata";
    audio.src = url;
  });
}

