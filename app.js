function requestLocalMedia(options = {}) {
  return new Promise((resolve) => {
    const input = document.createElement("input");
    input.type = "file";
    input.multiple = Boolean(options.multiple);
    input.accept = (options.accept || ["image"]).map((item) => `${item}/*`).join(",");
    input.addEventListener("change", () => {
      const files = [...input.files];
      Promise.all(files.map(uploadFile))
        .then((items) => resolve(options.multiple ? items : items[0] || null))
        .catch((error) => {
          addMessage("ai", format(t("uploadError"), { message: error.message || "unknown" }), "soul");
          resolve(options.multiple ? [] : null);
        })
        .finally(() => input.remove());
    });
    input.click();
  });
}

function fileToDataUrl(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result || ""));
    reader.onerror = () => reject(reader.error || new Error("read_failed"));
    reader.readAsDataURL(file);
  });
}

async function uploadFile(file) {
  const dataUrl = await fileToDataUrl(file);
  const uploaded = await apiFetch("/api/uploads", {
    method: "POST",
    body: JSON.stringify({
      name: file.name,
      type: file.type || "application/octet-stream",
      data: dataUrl,
    }),
  });
  return {
    type: uploaded.type || (file.type.startsWith("video") ? "video" : "image"),
    src: uploaded.src,
    title: uploaded.title || file.name,
    note: "",
  };
}

