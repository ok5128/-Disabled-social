function stopSpeech() {
  if (currentAudio) {
    currentAudio.pause();
    currentAudio = null;
  }
  if (currentSpeech && "speechSynthesis" in window) {
    window.speechSynthesis.cancel();
  }
  currentSpeech = null;
}

function playVoiceBubble(voice) {
  const wasPlaying = voice.dataset.playing === "true";
  chatMessages.querySelectorAll(".voice-bubble.is-playing").forEach((item) => {
    if (item !== voice) {
      item.classList.remove("is-playing");
      item.dataset.playing = "false";
    }
  });
  stopSpeech();
  if (wasPlaying) {
    voice.dataset.playing = "false";
    voice.classList.remove("is-playing");
    return;
  }

  voice.dataset.playing = "true";
  voice.classList.add("is-playing");
  const audioSrc = voice.dataset.audioSrc;
  if (audioSrc) {
    currentAudio = new Audio(audioSrc);
    currentAudio.addEventListener("ended", () => {
      voice.dataset.playing = "false";
      voice.classList.remove("is-playing");
      currentAudio = null;
    });
    currentAudio.play().catch(() => {
      voice.dataset.playing = "false";
      voice.classList.remove("is-playing");
      currentAudio = null;
      addMessage("ai", t("playbackError"), "soul");
    });
    return;
  }

  const spokenText = voice.dataset.spokenText || t("voiceMessage");
  if ("speechSynthesis" in window) {
    currentSpeech = new SpeechSynthesisUtterance(spokenText);
    currentSpeech.lang = lang === "zh" ? "zh-CN" : "en-US";
    currentSpeech.rate = 0.96;
    currentSpeech.pitch = 1;
    currentSpeech.onend = () => {
      voice.dataset.playing = "false";
      voice.classList.remove("is-playing");
      currentSpeech = null;
    };
    currentSpeech.onerror = () => {
      voice.dataset.playing = "false";
      voice.classList.remove("is-playing");
      currentSpeech = null;
      addMessage("ai", t("playbackError"), "soul");
    };
    window.speechSynthesis.resume?.();
    window.speechSynthesis.speak(currentSpeech);
  } else {
    voice.dataset.playing = "false";
    voice.classList.remove("is-playing");
    addMessage("ai", t("playbackError"), "soul");
  }
}

