function searchScore(spirit, keyword) {
  const loweredName = displayName(spirit).toLowerCase();
  const fields = [
    loweredName,
    text(spirit.type).toLowerCase(),
    text(spirit.line).toLowerCase(),
    text(spirit.intro).toLowerCase(),
  ];
  let score = 0;
  if (loweredName === keyword) score += 80;
  if (loweredName.startsWith(keyword)) score += 40;
  fields.forEach((field, index) => {
    if (!field.includes(keyword)) return;
    score += index === 0 ? 24 : 10;
  });
  return score + hotScore(spirit) / 1000;
}

function visibleSpirits() {
  const keyword = contactSearch.trim().toLowerCase();
  const fixedIds = ["dao", "awakening"];
  const fixed = fixedIds.map((id) => spirits.find((spirit) => spirit.id === id)).filter(Boolean);
  const sortable = spirits.filter((spirit) => !fixedIds.includes(spirit.id));
  const ordered = sortable.sort((a, b) => {
    if (contactMode === "hot") return hotScore(b) - hotScore(a);
    if (contactMode === "nearest") return distanceScore(a) - distanceScore(b);
    if (contactMode === "last") return lastContactScore(b) - lastContactScore(a);
    return hotScore(b) - hotScore(a);
  });
  const allOrdered = [...fixed, ...ordered];
  if (contactMode !== "search" || !contactSearchSubmitted || !keyword) return allOrdered;
  return allOrdered
    .filter((spirit) => {
      const haystack = [
        displayName(spirit),
        text(spirit.type),
        text(spirit.line),
        text(spirit.intro),
      ]
        .join(" ")
        .toLowerCase();
      return haystack.includes(keyword);
    })
    .sort((a, b) => searchScore(b, keyword) - searchScore(a, keyword));
}

